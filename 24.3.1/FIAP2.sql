/* =====================================================================
   DevBank - Script de setup do ambiente
   ---------------------------------------------------------------------
   Cria o schema da fintech ficticia "DevBank" e carrega dados de teste.

   - Pode ser executado quantas vezes quiser: apaga e recria as TABELAS.
     As functions/procedures que voce criou NAO sao apagadas (elas ficam
     INVALID por um instante e recompilam sozinhas no proximo uso).
   - Compativel com Oracle 12c ou superior (19c, 21c, Oracle Database Free,
     FreeSQL).
   - No SQL Developer, rode com F5 ("Executar Script"), nao com Ctrl+Enter.
   - Os dados nao tem acentos de proposito, para evitar problema de
     encoding em alguns clientes SQL.
   ===================================================================== */

-- ---------------------------------------------------------------------
-- 0. Limpeza (permite rodar o script de novo para "resetar" os dados)
-- ---------------------------------------------------------------------
BEGIN
  FOR t IN (SELECT table_name
              FROM user_tables
             WHERE table_name IN ('LOG_AUDITORIA', 'TRANSACOES', 'CHAVES_PIX',
                                  'CONTAS', 'CLIENTES')) LOOP
    EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
  END LOOP;
END;
/

-- ---------------------------------------------------------------------
-- 1. Tabelas
-- ---------------------------------------------------------------------
CREATE TABLE clientes (
  id_cliente      NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100)
                  CONSTRAINT pk_clientes PRIMARY KEY,
  nome            VARCHAR2(100) NOT NULL,
  cpf             VARCHAR2(11)  NOT NULL CONSTRAINT uk_clientes_cpf UNIQUE,  -- so digitos
  email           VARCHAR2(100) NOT NULL,
  telefone        VARCHAR2(20),
  data_nascimento DATE          NOT NULL,
  renda_mensal    NUMBER(12,2)  NOT NULL,
  score_credito   NUMBER(4)     NOT NULL
                  CONSTRAINT ck_clientes_score CHECK (score_credito BETWEEN 0 AND 1000),
  status          VARCHAR2(10)  DEFAULT 'ATIVO' NOT NULL
                  CONSTRAINT ck_clientes_status CHECK (status IN ('ATIVO', 'INATIVO')),
  data_cadastro   DATE          DEFAULT SYSDATE NOT NULL
);

CREATE TABLE contas (
  id_conta          NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 2000)
                    CONSTRAINT pk_contas PRIMARY KEY,
  id_cliente        NUMBER NOT NULL
                    CONSTRAINT fk_contas_cliente REFERENCES clientes (id_cliente),
  tipo              VARCHAR2(10) NOT NULL
                    CONSTRAINT ck_contas_tipo CHECK (tipo IN ('CORRENTE', 'POUPANCA')),
  saldo             NUMBER(15,2) DEFAULT 0 NOT NULL
                    CONSTRAINT ck_contas_saldo CHECK (saldo >= 0),   -- defesa em profundidade
  limite_pix_diario NUMBER(15,2) DEFAULT 1000 NOT NULL,
  status            VARCHAR2(10) DEFAULT 'ATIVA' NOT NULL
                    CONSTRAINT ck_contas_status CHECK (status IN ('ATIVA', 'BLOQUEADA', 'ENCERRADA')),
  data_abertura     DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE chaves_pix (
  chave        VARCHAR2(100) CONSTRAINT pk_chaves_pix PRIMARY KEY,
  tipo_chave   VARCHAR2(10)  NOT NULL
               CONSTRAINT ck_chaves_tipo CHECK (tipo_chave IN ('CPF', 'EMAIL', 'TELEFONE', 'ALEATORIA')),
  id_conta     NUMBER NOT NULL
               CONSTRAINT fk_chaves_conta REFERENCES contas (id_conta),
  data_criacao DATE DEFAULT SYSDATE NOT NULL
);

-- DEPOSITO: so conta destino | SAQUE/TARIFA: so conta origem | PIX: as duas
CREATE TABLE transacoes (
  id_transacao     NUMBER GENERATED BY DEFAULT AS IDENTITY
                   CONSTRAINT pk_transacoes PRIMARY KEY,
  id_conta_origem  NUMBER CONSTRAINT fk_transacoes_origem  REFERENCES contas (id_conta),
  id_conta_destino NUMBER CONSTRAINT fk_transacoes_destino REFERENCES contas (id_conta),
  tipo             VARCHAR2(10) NOT NULL
                   CONSTRAINT ck_transacoes_tipo CHECK (tipo IN ('PIX', 'DEPOSITO', 'SAQUE', 'TARIFA')),
  valor            NUMBER(15,2) NOT NULL
                   CONSTRAINT ck_transacoes_valor CHECK (valor > 0),
  status           VARCHAR2(10) DEFAULT 'CONCLUIDA' NOT NULL
                   CONSTRAINT ck_transacoes_status CHECK (status IN ('CONCLUIDA', 'RECUSADA')),
  motivo_recusa    VARCHAR2(200),
  data_hora        DATE DEFAULT SYSDATE NOT NULL
);

CREATE TABLE log_auditoria (
  id_log    NUMBER GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_log_auditoria PRIMARY KEY,
  nivel     VARCHAR2(10)   NOT NULL,          -- INFO / ERRO
  origem    VARCHAR2(60)   NOT NULL,          -- nome da rotina que gerou o log
  mensagem  VARCHAR2(4000),
  usuario   VARCHAR2(128)  DEFAULT USER NOT NULL,
  data_hora DATE           DEFAULT SYSDATE NOT NULL
);

-- Indices que as rotinas do dia a dia vao usar
CREATE INDEX ix_contas_cliente         ON contas (id_cliente);
CREATE INDEX ix_chaves_pix_conta       ON chaves_pix (id_conta);
CREATE INDEX ix_transacoes_origem_data ON transacoes (id_conta_origem, data_hora);

