-- ---------------------------------------------------------------------
-- 3. Codigo "legado" da empresa que voce vai reutilizar
--    Grava log de auditoria em uma TRANSACAO AUTONOMA: o log fica gravado
--    mesmo que a rotina que chamou faca ROLLBACK depois.
-- ---------------------------------------------------------------------
CREATE OR REPLACE PROCEDURE sp_log (
  p_nivel    IN VARCHAR2,
  p_origem   IN VARCHAR2,
  p_mensagem IN VARCHAR2
) IS
  PRAGMA AUTONOMOUS_TRANSACTION;
BEGIN
  INSERT INTO log_auditoria (nivel, origem, mensagem)
  VALUES (p_nivel, p_origem, SUBSTR(p_mensagem, 1, 4000));
  COMMIT;
END sp_log;
